#!/usr/bin/env python3
"""Turn each sign clip into one JPG sprite sheet the TV app animates with a plain <Image> (no video decoder).

Why: w3cmedia video never played on the real Vega stick (stuck), and on the VVD it drew zoomed/cropped/frozen.
A sprite sheet shows the same real Deaf signer, loops reliably and needs no network or media services.

Usage (Windows, from D:\\fs-vega):  python scripts/make-sprites.py
Reads  ../first-signs/model/export/videos/<id>.mp4 (override with FS_MODEL_EXPORT)
Writes src/generated/sprites/<id>.jpg and src/generated/sprites.ts
"""
import json
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
EXPORT = Path(os.environ.get("FS_MODEL_EXPORT", r"C:\Users\Fatal\Desktop\Hackathons\amazon-build-ship-shape\first-signs\model\export"))
VIDEOS = EXPORT / "videos"
OUT = ROOT / "src" / "generated" / "sprites"
FFMPEG = os.environ.get("FFMPEG", r"C:\ffmpeg\bin\ffmpeg.exe")
FPS = 12
FRAME_H = int(os.environ.get("FRAME_H", "240"))  # 2026-10-23: was 320 (decoded sheets up to 7.6 MB each; the real stick ran out of graphics memory)
MAX_SHEET = int(os.environ.get("MAX_SHEET", "1024"))  # was 2048; 1024 keeps each decoded sheet <= ~4 MB on the 1 GB stick
QUALITY = 78


def frames_of(mp4: Path, tmp: Path) -> list[Path]:
    for f in tmp.glob("*.jpg"):
        f.unlink()
    subprocess.run(
        [FFMPEG, "-v", "error", "-y", "-i", str(mp4), "-vf", f"fps={FPS},scale=-2:{FRAME_H}:flags=lanczos",
         "-q:v", "2", str(tmp / "f%03d.jpg")],
        check=True,
    )
    return sorted(tmp.glob("f*.jpg"))


def main() -> int:
    if not VIDEOS.is_dir():
        print(f"no videos at {VIDEOS}", file=sys.stderr)
        return 1
    if OUT.exists():
        shutil.rmtree(OUT)
    OUT.mkdir(parents=True)
    meta = {}
    total = 0
    with tempfile.TemporaryDirectory() as td:
        tmp = Path(td)
        for mp4 in sorted(VIDEOS.glob("*.mp4")):
            sid = mp4.stem
            frames = frames_of(mp4, tmp)
            if not frames:
                print(f"skip {sid}: no frames", file=sys.stderr)
                continue
            fw, fh = Image.open(frames[0]).size
            cols = max(1, min(len(frames), MAX_SHEET // fw))
            rows = -(-len(frames) // cols)
            if rows * fh > MAX_SHEET:
                print(f"{sid}: {len(frames)} frames do not fit a {MAX_SHEET}px sheet; truncating", file=sys.stderr)
                rows = MAX_SHEET // fh
                frames = frames[: rows * cols]
            sheet = Image.new("RGB", (cols * fw, rows * fh), (0, 0, 0))
            for i, f in enumerate(frames):
                sheet.paste(Image.open(f).convert("RGB"), ((i % cols) * fw, (i // cols) * fh))
            dst = OUT / f"{sid}.jpg"
            sheet.save(dst, "JPEG", quality=QUALITY, optimize=True, progressive=False)
            total += dst.stat().st_size
            meta[sid] = {"n": len(frames), "cols": cols, "rows": rows, "fw": fw, "fh": fh}
            print(f"{sid}: {len(frames)} frames, {cols}x{rows} of {fw}x{fh}, {dst.stat().st_size // 1024} KB")

    lines = [
        "// GENERATED by scripts/make-sprites.py - do not edit.",
        f"// One JPG sprite sheet per sign clip: n frames at {FPS} fps, laid out row-major in cols x rows cells of fw x fh px.",
        f"export const SPRITE_FPS = {FPS};",
        "export type Sprite = { src: any; n: number; cols: number; rows: number; fw: number; fh: number };",
        "export const SPRITES: Record<string, Sprite> = {",
    ]
    for sid, m in meta.items():
        lines.append(
            f"  {json.dumps(sid)}: {{ src: require('./sprites/{sid}.jpg'), n: {m['n']}, cols: {m['cols']}, rows: {m['rows']}, fw: {m['fw']}, fh: {m['fh']} }},"
        )
    lines.append("};")
    (ROOT / "src" / "generated" / "sprites.ts").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(meta)} sheets, {total / 1e6:.1f} MB")
    return 0


if __name__ == "__main__":
    sys.exit(main())

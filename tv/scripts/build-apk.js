#!/usr/bin/env node
// Builds a standalone release APK (JS bundle embedded, debug-signed) for Fire TV / Android TV.
//
// Why the mirror: on Windows, CMake/ninja object paths under a long Desktop path exceed 260 chars and the
// native modules fail ("build.ninja still dirty after 100 tries"). So we mirror this folder to a short
// path (FS_BUILD_DIR, default D:\fs-tv), prebuild + gradle there, and copy the APK back into dist/.
// On macOS/Linux set FS_BUILD_DIR=. to build in place.
//
//   node scripts/build-apk.js                 # armeabi-v7a, arm64-v8a, x86 (x86 = Android TV emulator)
//   FS_ABIS=armeabi-v7a,arm64-v8a node scripts/build-apk.js
//   FS_SERVER_URL=ws://192.168.0.60:8788/ws node scripts/build-apk.js
const { execSync } = require('child_process');
const fs = require('fs');
const path = require('path');

const SRC = path.resolve(__dirname, '..');
const BUILD = path.resolve(process.env.FS_BUILD_DIR || (process.platform === 'win32' ? 'D:\\fs-tv' : SRC));
const ABIS = process.env.FS_ABIS || 'armeabi-v7a,arm64-v8a,x86';
const env = {
  ...process.env,
  EXPO_TV: '1',
  FS_ABIS: ABIS,
  GRADLE_USER_HOME: process.env.GRADLE_USER_HOME || (process.platform === 'win32' ? 'D:\\AndroidBuild\\gradle-home' : undefined),
  NODE_ENV: 'production',
};
if (!env.GRADLE_USER_HOME) delete env.GRADLE_USER_HOME;
const run = (cmd, cwd) => {
  console.log(`\n$ ${cmd}   (in ${cwd})`);
  execSync(cmd, { cwd, env, stdio: 'inherit' });
};

run('node scripts/sync-model.js && node scripts/write-config.js', SRC);

if (BUILD !== SRC) {
  fs.mkdirSync(BUILD, { recursive: true });
  // android/ in the build dir is generated by prebuild, so it's excluded from the copy.
  // Full paths only: a bare "android" would also skip node_modules/**/android folders.
  const top = ['android', 'ios', 'dist', 'dist-web', 'dist-web-next', 'dist-web-prev', 'docs', '.expo', '.git'];
  const xd = [...top.map((d) => path.join(SRC, d)), path.join(BUILD, 'android')].map((d) => `"${d}"`).join(' ');
  try {
    // /E /XX (not /MIR): copy changes but never delete Gradle outputs that live in node_modules/*/android/build.
    execSync(`robocopy "${SRC}" "${BUILD}" /E /XX /XD ${xd} /NFL /NDL /NJH /NJS /NP /R:1 /W:1`, { stdio: 'inherit' });
  } catch (e) {
    if (e.status >= 8) throw e; // robocopy exit codes < 8 mean success
  }
}

// --clean only on the first build (or FS_CLEAN=1) so Gradle's incremental outputs survive later builds.
const clean = process.env.FS_CLEAN === '1' || !fs.existsSync(path.join(BUILD, 'android'));
run(`npx expo prebuild --platform android ${clean ? '--clean ' : ''}--no-install`, BUILD);
const gradlew = process.platform === 'win32' ? '.\\gradlew.bat' : './gradlew';
run(`${gradlew} assembleRelease --no-daemon -PreactNativeArchitectures=${ABIS}`, path.join(BUILD, 'android'));

const apk = path.join(BUILD, 'android', 'app', 'build', 'outputs', 'apk', 'release', 'app-release.apk');
const outDir = path.join(SRC, 'dist');
fs.mkdirSync(outDir, { recursive: true });
const out = path.join(outDir, 'first-signs.apk');
fs.copyFileSync(apk, out);
console.log(`\nAPK: ${out} (${(fs.statSync(out).size / 1e6).toFixed(1)} MB)`);
